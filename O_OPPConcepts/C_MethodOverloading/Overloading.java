package O_OPPConcepts.C_MethodOverloading;

public class Overloading {

/* Method overloading is producing a new method with:
        - same name
        - different data type
*/
    public int add (int a, int b){
        return a + b;
    }

    public double add (double b, double a){
        return a + b;
    }
}
